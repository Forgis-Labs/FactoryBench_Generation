"""Consolidate KUKA Q&A shards on HF into a single test.jsonl per level.

Background: the KUKA industrial-episodes Q&A were generated by streaming
shards to `Forgis/FactoryBench_QA_pairs:factorywave_kuka_qa_260/level_<N>/`
under names like `level1_shard_0015.jsonl`. The `scripts.eval_test_set`
orchestrator expects the concatenated `level_<N>/test.jsonl` file that the
UR3 track uses, so this script pulls all shards for each level and merges
them into that expected filename (uploaded back to the same folder).

After running this, the industrial eval can be launched with:

    python -m scripts.eval_test_set \\
        --repo-id Forgis/FactoryBench_QA_pairs \\
        --hf-dataset-folder factorywave_kuka_qa_260 \\
        --levels 1 2 3 4 \\
        --models gpt-5.1-1 claude-sonnet-4.6 mistral-large-3 \\
                 deepseek-v3.2 qwen-3-235b qwen-3-4b \\
        --output-root output/kuka_eval

The KUKA panel scores can then be reported as the "industrial-generalisation"
counterpart to the paper's UR3-only test-split numbers (reviewer W.2).
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

try:
    from huggingface_hub import HfApi, hf_hub_download, upload_file
except ImportError:
    print("ERROR: install huggingface_hub before running this script.", file=sys.stderr)
    sys.exit(1)

try:
    from dotenv import load_dotenv
    load_dotenv()
except ImportError:
    pass

import os as _os
# Prefer the write token when uploading; fall back to read token for pulling
if _os.getenv("HF_WRITE_TOKEN") and not _os.getenv("HF_TOKEN"):
    _os.environ["HF_TOKEN"] = _os.environ["HF_WRITE_TOKEN"]


DEFAULT_REPO_ID = "Forgis/FactoryBench_QA_pairs"
DEFAULT_FOLDER = "factorywave_kuka_qa_260"


def _list_shards(api: HfApi, repo_id: str, folder: str, level: int, token: str | None = None) -> list[str]:
    prefix = f"{folder}/level_{level}/"
    all_files = api.list_repo_files(repo_id, repo_type="dataset", token=token)
    shards = [
        f for f in all_files
        if f.startswith(prefix)
        and f.endswith(".jsonl")
        and "shard" in Path(f).name
    ]
    return sorted(shards)


def _pull_and_merge(
    api: HfApi,
    repo_id: str,
    folder: str,
    level: int,
    out_dir: Path,
) -> Path | None:
    shards = _list_shards(api, repo_id, folder, level, api.token)
    if not shards:
        print(f"  L{level}: no shards found under {folder}/level_{level}/", file=sys.stderr)
        return None
    local_out = out_dir / f"level_{level}_test.jsonl"
    n_items = 0
    with open(local_out, "w", encoding="utf-8") as w:
        for remote in shards:
            local_shard = hf_hub_download(repo_id, remote, repo_type="dataset", token=api.token)
            with open(local_shard, encoding="utf-8") as r:
                for line in r:
                    line = line.strip()
                    if not line:
                        continue
                    # sanity-parse
                    json.loads(line)
                    w.write(line + "\n")
                    n_items += 1
    print(f"  L{level}: merged {len(shards)} shards -> {local_out} ({n_items} items)")
    return local_out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo-id", default=DEFAULT_REPO_ID)
    ap.add_argument("--folder", default=DEFAULT_FOLDER)
    ap.add_argument("--levels", nargs="+", type=int, default=[1, 2, 3, 4])
    ap.add_argument("--stage-dir", type=Path, default=Path("output/kuka_stage"))
    ap.add_argument(
        "--upload",
        action="store_true",
        help="After merging, upload each level's test.jsonl back to HF so "
             "eval_test_set can pull it as it does for the UR3 track.",
    )
    args = ap.parse_args()

    args.stage_dir.mkdir(parents=True, exist_ok=True)
    token = _os.getenv("HF_WRITE_TOKEN") or _os.getenv("HF_TOKEN") or _os.getenv("HF_API_TOKEN")
    if not token:
        print("ERROR: no HF token found in env (HF_TOKEN / HF_WRITE_TOKEN / HF_API_TOKEN)", file=sys.stderr)
        return 1
    api = HfApi(token=token)

    for lvl in args.levels:
        local = _pull_and_merge(api, args.repo_id, args.folder, lvl, args.stage_dir)
        if local is None or not args.upload:
            continue
        remote = f"{args.folder}/level_{lvl}/test.jsonl"
        upload_file(
            path_or_fileobj=str(local),
            path_in_repo=remote,
            repo_id=args.repo_id,
            repo_type="dataset",
            commit_message=f"rebuttal: consolidated KUKA level {lvl} shards into test.jsonl",
        )
        print(f"  L{lvl}: uploaded -> {args.repo_id}:{remote}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
